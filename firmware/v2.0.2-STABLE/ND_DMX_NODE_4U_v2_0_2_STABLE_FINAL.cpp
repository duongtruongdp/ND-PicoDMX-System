  // Wait for the Core 0 system to be ready to use the Pico SDK Memory Barrier
  if (!systemReady) {
    while (!systemReady) {
      asm volatile("wfe");
    }
    asm volatile("dmb" : : : "memory");
  }

  __atomic_fetch_add(&lCount1, 1u, __ATOMIC_RELAXED);
  __atomic_fetch_add(&core1_heartbeat, 1u, __ATOMIC_RELAXED);
  
  for (int i = 0; i < 4; i++) {
    if (cfg.portEnabled[i] == 1) {
      handleDmxTransmit(i);
    }
  }
