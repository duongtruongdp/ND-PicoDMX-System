// DMX statefuls transmission system is non-blocking and multi-thread safe
void handleDmxTransmit(int i) {
  const uint32_t nowMs = millis();
  const uint32_t nowUs = micros();
  const uint pin = RS485_PINS[i];

  switch (ports[i].state) {
    case STATE_IDLE: {
      const int32_t timeRemaining =
          static_cast<int32_t>(ports[i].nextFrameTimeUs - nowUs);

      // Only enter the shared-buffer critical section when a new frame is
      // actually due. This reduces spinlock traffic from hundreds of thousands
      // of claims per second to about 160 short claims per second (4 x 40 Hz).
      if (timeRemaining <= 0) {
        const uint32_t irqStatus = spin_lock_blocking(dmx_lock);

        const uint8_t testMode = ports[i].testMode;
        if (testMode == TEST_BLACKOUT) {
          memset(ports[i].activeDmxBuffer, 0, 513);
        } else if (testMode == TEST_HALF) {
          ports[i].activeDmxBuffer[0] = 0;
          memset(ports[i].activeDmxBuffer + 1, 128, 512);
        } else if (testMode == TEST_FULL) {
          ports[i].activeDmxBuffer[0] = 0;
          memset(ports[i].activeDmxBuffer + 1, 255, 512);
        } else if (testMode == TEST_CHASE) {
          if (nowMs - ports[i].lastChaseStepMs >= 100) {
            ports[i].chaseChannel++;
            if (ports[i].chaseChannel > 512) {
              ports[i].chaseChannel = 1;
            }
            ports[i].lastChaseStepMs = nowMs;
          }

          memset(ports[i].activeDmxBuffer, 0, 513);
          ports[i].activeDmxBuffer[ports[i].chaseChannel] = 255;
        } else if (ports[i].hasNewData) {
          memcpy(ports[i].activeDmxBuffer, ports[i].dmxBuffer, 513);
          ports[i].hasNewData = false;
        }

        spin_unlock(dmx_lock, irqStatus);

        // The 25 ms period is measured from BREAK start: approximately 40 Hz.
        ports[i].nextFrameTimeUs = nowUs + 25000u;

        // Generate the DMX BREAK with SIO.
        pinMode(pin, OUTPUT);
        digitalWrite(pin, LOW);

        ports[i].state = STATE_BREAK;
        ports[i].stateStartTimeUs = nowUs;
        __atomic_fetch_add(
            &ports[i].dmxFrameCount, 1u, __ATOMIC_RELAXED);
      }
      break;
    }

    case STATE_BREAK:
      // DMX512 requires at least 88 us BREAK.
      if (static_cast<uint32_t>(
              nowUs - ports[i].stateStartTimeUs) >= 105u) {
        digitalWrite(pin, HIGH);
        ports[i].state = STATE_MAB;
        ports[i].stateStartTimeUs = nowUs;
      }
      break;

    case STATE_MAB:
      // DMX512 requires at least 8 us Mark After Break.
      if (static_cast<uint32_t>(
              nowUs - ports[i].stateStartTimeUs) >= 14u) {
        dmxOutputs[i].reset_sm();
        ports[i].state = STATE_SENDING;
        ports[i].stateStartTimeUs = nowUs;
        ports[i].txIndex = 0;
      }
      break;

    case STATE_SENDING: {
      uint8_t fed = 0;
      while (ports[i].txIndex < 513 && fed < 16) {
        if (!dmxOutputs[i].put_byte(
                ports[i].activeDmxBuffer[ports[i].txIndex])) {
          break;
        }

        ports[i].txIndex++;
        fed++;
      }

      if (ports[i].txIndex >= 513) {
        ports[i].state = STATE_IDLE;
      } else if (static_cast<uint32_t>(
                     nowUs - ports[i].stateStartTimeUs) > 35000u) {
        // A full 513-slot DMX frame is normally about 22.7 ms. Recover a
        // stalled PIO/FIFO instead of leaving Core 1 stuck indefinitely.
        dmxOutputs[i].reset_sm();
        ports[i].txIndex = 0;
        ports[i].state = STATE_IDLE;
        ports[i].nextFrameTimeUs = nowUs + 1000u;
      }
      break;
    }

    default:
      dmxOutputs[i].reset_sm();
      ports[i].txIndex = 0;
      ports[i].state = STATE_IDLE;
      ports[i].nextFrameTimeUs = nowUs + 1000u;
      break;
  }
}

